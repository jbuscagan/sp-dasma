import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { extractLetter, findDates, splitPages } from './extract';
import { parseTransmittalPage, splitOrgBarangay } from './tableParse';
import { pageTextItems } from './pdfText';
import { setFontSource } from '@/lib/pdfFonts';
import { buildReport } from '@/features/reports/build';
import { buildHeader } from '@/features/reports/header';
import { renderPdf } from '@/features/reports/pdf';
import { TYPES } from '@/features/transmittal/config';
import type { Committee, Entry } from '@/lib/types';

const BARANGAYS = ['Burol Main', 'Saint Peter I', 'Salitran II', 'Salitran IV', 'Zone II', 'Luzviminda II', 'San Nicolas I', 'Sampaloc III'];
const ORGS = ['KBDM', 'Senior Citizens Association', 'Dasmariñas ThirdGen'];

const LETTER_1 = `November 3, 2026

HON. ROBIN CHESTER J. CANTIMBUHAN
Sangguniang Panlungsod Member
City of Dasmariñas

Dear Sir,

Greetings! The KBDM Chapter of Brgy. Salitran II will hold our Christmas Party on December 20, 2026.
In line with this, we humbly ask for financial assistance and raffle prizes for our members.

For questions you may contact me at 0917 123 4567.

Respectfully yours,

JUAN DELA CRUZ
President, KBDM Salitran II`;

const LETTER_2 = `October 12, 2026
Magandang araw po!
Ako po ay humihingi ng tulong para sa hospital bill ng aking anak na diagnosed with Bullous Cellulitis.
Kami po ay taga Sampaloc III. Cel: 09171123781
Maraming salamat po,
Sonny C. Autencio`;

describe('letter extraction', () => {
  it('reads a typical solicitation letter', () => {
    const x = extractLetter(LETTER_1, { barangays: BARANGAYS, orgs: ORGS, medical: false });
    expect(x.name.value).toBe('Juan Dela Cruz');
    expect(x.organization).toEqual({ value: 'KBDM', confidence: 'high' });
    expect(x.barangay).toEqual({ value: 'Salitran II', confidence: 'high' });
    expect(x.request.value).toBe('Cash/Raffle');
    expect(x.purpose.value).toBe('Christmas Party');
    expect(x.dateReceived.value).toBe('2026-11-03');
    expect(x.eventDate.value).toBe('December 20, 2026');
    expect(x.contact).toEqual({ value: '09171234567', confidence: 'high' });
  });

  it('reads a Taglish medical letter', () => {
    const x = extractLetter(LETTER_2, { barangays: BARANGAYS, orgs: ORGS, medical: true });
    expect(x.name.value).toBe('Sonny C. Autencio');
    expect(x.barangay.value).toBe('Sampaloc III');
    expect(x.purpose.value).toBe('For Hospital Bill');
    expect(x.diagnosis.value).toBe('Bullous Cellulitis');
    expect(x.contact.value).toBe('09171123781');
    expect(x.dateReceived.value).toBe('2026-10-12');
  });

  it('keeps only the organization name when it is not in the list yet', () => {
    const x = extractLetter(LETTER_1, { barangays: BARANGAYS, orgs: [], medical: false });
    expect(x.organization).toEqual({ value: 'KBDM Chapter', confidence: 'medium' });
  });

  it('finds dates written in different ways', () => {
    expect(findDates('on 20 November 2026 and 11/21/26').map((d) => d.iso)).toEqual(['2026-11-20', '2026-11-21']);
  });

  it('splits a multi-page PDF into separate letters', () => {
    const p2cont = 'and we hope for your kind support. Thank you and God bless.\nMARIA SANTOS';
    expect(splitPages([LETTER_2, LETTER_1, 'Dear Sir,\nrequest for our league', p2cont])).toEqual([[0], [1], [2, 3]]);
  });
});

describe('prepared transmittal PDFs', () => {
  const pub = path.resolve(__dirname, '../../../public');
  setFontSource(async (file) => readFileSync(`${pub}/fonts/${file}`).toString('base64'));

  it('recognizes the kind of transmittal from its code or title', async () => {
    const { detectTransmittalType } = await import('./tableParse');
    expect(detectTransmittalType('SPMRC-MA-041 TRANSMITTAL OF MEDICAL ASSISTANCE REQUEST')).toBe('medical');
    expect(detectTransmittalType('SPMRC-BRGY-043 TRANSMITTAL OF SOLICITATION REQUEST (SK)')).toBe('sk');
    expect(detectTransmittalType('SPMRC-NGO-CH-044 TRANSMITTAL OF SOLICITATION REQUESTS – NGO')).toBe('christmas');
    expect(detectTransmittalType('SPMRC-BRGY-044 TRANSMITTAL OF SOLICITATION REQUESTS – BARANGAY')).toBe('barangay');
    expect(detectTransmittalType('SPMRC-NGO-044 TRANSMITTAL OF SOLICITATION REQUESTS – NGO')).toBe('ngo');
  });

  it('splits "Organization - Barangay"', () => {
    expect(splitOrgBarangay('Senior Citizens Ass. - St. Peter I', BARANGAYS)).toEqual({ organization: 'Senior Citizens Ass.', barangay: 'Saint Peter I' });
    expect(splitOrgBarangay('Luzviminda 2', BARANGAYS)).toEqual({ organization: '', barangay: 'Luzviminda II' });
    expect(splitOrgBarangay('EAC - Marketing and Communication Office', BARANGAYS)).toEqual({ organization: 'EAC - Marketing and Communication Office', barangay: '' });
  });

  it('reads back a report generated by this system', async () => {
    const committee: Committee = { id: 'c', name: 'Office of SPM Robin Cantimbuhan', spm_name: 'Robin Cantimbuhan', code_prefix: 'SPMRC' };
    const base = { committee_id: 'c', type: 'christmas', patient_name: null, request_details: null, diagnosis: null, assistance_spec: null, remarks: null, assistance_status: 'pending', assistance_date: null, status: 'draft', archived_reason: null, transmittal_id: null, attachment_paths: [] as string[], position: null, submitted_at: null, received_by: null, received_at: null, created_at: '', updated_at: '', organization_id: null, barangay_id: null, received_committee_id: null } as const;
    const entries: Entry[] = [
      { ...base, id: '1', date_received: '2026-10-29', solicitor_name: 'Glenda Sescar', organization: 'Dasmariñas ThirdGen', barangay: 'Burol Main', purpose: 'Christmas Party', request: 'Cash/In-Kind', contact_number: '09388293438', event_date: 'December 13, 2026' },
      { ...base, id: '2', date_received: '2026-10-30', solicitor_name: 'Antonio B. Elauria', organization: 'Senior Citizens Association', barangay: 'Saint Peter I', purpose: 'Christmas Party', request: 'Cash', contact_number: '09491388861', event_date: 'December 20, 2026' },
    ];
    const doc = buildReport({ header: buildHeader('christmas', committee, entries, '2026-11-05'), columns: TYPES.christmas.columns, entries, headerColor: '#ff0000', headerText: '#000000', encoderName: 'J', encoderPosition: 'AA', paper: 'A4', orientation: 'landscape' });
    const pdf = new Uint8Array(await (await renderPdf(doc)).arrayBuffer());
    const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs');
    const page = await (await pdfjs.getDocument({ data: pdf }).promise).getPage(1);
    const rows = parseTransmittalPage(await pageTextItems(page));
    expect(rows).toHaveLength(2);
    expect(rows[0]).toMatchObject({ date_received: '2026-10-29', solicitor_name: 'Glenda Sescar', contact_number: '09388293438', event_date: 'December 13, 2026', purpose: 'Christmas Party' });
    expect(splitOrgBarangay(rows[1].orgBarangay ?? '', BARANGAYS)).toEqual({ organization: 'Senior Citizens Association', barangay: 'Saint Peter I' });
  }, 30000);
});

describe('duplicate checks', async () => {
  const { findDuplicate, batchDuplicates } = await import('./duplicates');
  const e = { id: 'x', committee_id: 'c1', solicitor_name: 'Juan Dela Cruz', patient_name: null, organization: 'KBDM', contact_number: '09171234567', date_received: '2026-11-01' } as unknown as Entry;
  it('matches by phone + name / organization, ignoring spelling style', () => {
    expect(findDuplicate({ name: 'JUAN DELA CRUZ', organization: 'kbdm', contact: '+63 917 123 4567', dateReceived: '' }, [e], () => 'Office A')).toContain('Juan Dela Cruz');
    expect(findDuplicate({ name: 'Maria Santos', organization: 'PWD', contact: '09998887777', dateReceived: '' }, [e], () => 'Office A')).toBeNull();
  });
  it('finds the same request twice in one upload', () => {
    const m = batchDuplicates([
      { name: 'Ana', organization: 'KBDM', contact: '09170000001', dateReceived: '' },
      { name: 'Ben', organization: 'PWD', contact: '0917 000 0001', dateReceived: '' },
    ]);
    expect(m.get(1)).toBe(0);
  });
});
